def ask(phase_id: str, title: str, user_text: str):
    print(f"\n{'─'*60}")
    print(f"[{phase_id}] {title}")
    print("─" * 60)
    messages.append({"role": "user", "content": user_text})
    print("  Claude分析中...", end="", flush=True)
    resp = client.messages.create(
        model="claude-opus-4-8",
        max_tokens=3000,
        system=SYSTEM,
        messages=messages,
    )
    text = resp.content[0].text
    messages.append({"role": "assistant", "content": text})
    print(" 完了\n")
    print(text)
    results.append({"id": phase_id, "title": title, "response": text})
    return text


