def auto_fill(text):
    for ph, val in _STAR_MAP:
        text = text.replace(ph, val)
    for ph in re.findall(r"★[^\n]*", text):
        text = text.replace(ph, "（ここまでの分析から推定・補完してください）", 1)
    return text

